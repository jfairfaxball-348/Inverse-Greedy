def lean_fs(s):
    s = sorted(s)
    return "∅" if not s else "{" + ", ".join(map(str, s)) + "}"


def nb_of(n, edges):
    nb = [set() for _ in range(n)]
    for a, b in edges:
        nb[a].add(b); nb[b].add(a)
    return nb


def nb_lean(n, edges):
    return "![" + ", ".join(lean_fs(x) for x in nb_of(n, edges)) + "]"


def pair_rank(n, a, b):
    return a * (2 * n - a - 1) // 2 + (b - a - 1)


def G(n, edges):
    g = nx.Graph(); g.add_nodes_from(range(n)); g.add_edges_from(edges); return g


def qlit(x):
    x = Fraction(x)
    return f"{x.numerator}" if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


