"""Generate InverseGreedy/SmallGraphObstructions.lean.

The generated file is self-certifying: every path list is checked by
kernel `decide`, every closed form by `field_simp; ring`, and every
positivity certificate by `positivity`.  This script is a convenience
only; nothing it computes is trusted by Lean.
"""
import re
import sys
import os
import sympy as sp

sys.path.insert(0, os.path.dirname(__file__))
from lean_race_terms import race_terms, law, graph  # noqa: E402

R = sp.symbols('x0:6', positive=True)


def lean_fs(s):
    s = sorted(s)
    return "∅" if not s else "{" + ", ".join(map(str, s)) + "}"


def lean_terms(ts):
    return "[" + ", ".join(
        "[" + ", ".join(f"({v}, [{', '.join(map(str, S))}])" for v, S in t) + "]"
        for t in ts) + "]"


def to_lean(expr):
    s = sp.sstr(expr)
    s = re.sub(r"x(\d)", r"⟪\1⟫", s)
    s = s.replace("**", "^")
    s = re.sub(r"⟪(\d)⟫\^", r"(r \1)^", s)
    s = re.sub(r"⟪(\d)⟫", r"r \1", s)
    return s


def tag(T):
    return "".join(map(str, sorted(T))) or "empty"


HDR = """import InverseGreedy.RaceTerms
import InverseGreedy.C6Product
import InverseGreedy.P6Bottleneck
import InverseGreedy.CoronaP3Minor

/-!
# S041: genuine real-clock obstructions for P5, K1∨P5, C6, P6, corona(P3)

GENERATED by `experiments/gen_small_graph_obstructions.py`, but fully
self-certifying in Lean: path lists by kernel `decide`, closed forms by
`field_simp; ring`, sign certificates by `positivity`. Each final theorem
is `¬ RealClockEGU`, i.e. about Mathlib's genuine independent exponential
clocks, for **all** strictly positive real rate vectors.
-/

namespace InverseGreedy

/-- Specialisation of the certified expansion to `Fin n`. -/
theorem finiteRaceLaw_fin_eq {n : ℕ} (rates : Fin n → ℝ)
    (nb : Fin n → Finset (Fin n)) (fuel : ℕ) (A T : Finset (Fin n)) :
    finiteRaceLaw rates nb fuel A T =
      raceValue rates (raceTerms (List.finRange n) nb fuel A T) :=
  finiteRaceLaw_eq_raceValue _ (List.nodup_finRange n)
    (fun x => List.mem_finRange x) rates nb fuel A T

/-- Uniformity of the genuine real-clock law, read through the bridge. -/
theorem firstChoice_values_of_realClockEGU {n : ℕ}
    (nb : Fin n → Finset (Fin n))
    (hSymm : ∀ x y, y ∈ nb x → x ∈ nb y) (h : RealClockEGU nb) :
    ∃ rates : Fin n → ℝ, (∀ v, 0 < rates v) ∧
      ∀ I ∈ maximalIndependentSets nb,
        finiteRaceLaw rates nb n Finset.univ I =
          1 / ((maximalIndependentSets nb).card : ℝ) := by
  obtain ⟨rates, hpos, hI⟩ := (realClockEGU_iff_firstChoiceEGU nb hSymm).mp h
  refine ⟨rates, hpos, fun I hmem => ?_⟩
  simpa only [Fintype.card_fin] using hI I hmem

/-- A strict 2×2 minor among four maximal independent sets, valid for all
strictly positive rates, rules out genuine real-clock EGU. -/
theorem not_realClockEGU_of_strict_minor {n : ℕ}
    (nb : Fin n → Finset (Fin n))
    (hSymm : ∀ x y, y ∈ nb x → x ∈ nb y)
    (I J K L : Finset (Fin n))
    (hI : I ∈ maximalIndependentSets nb) (hJ : J ∈ maximalIndependentSets nb)
    (hK : K ∈ maximalIndependentSets nb) (hL : L ∈ maximalIndependentSets nb)
    (hminor : ∀ rates : Fin n → ℝ, (∀ v, 0 < rates v) →
      finiteRaceLaw rates nb n Finset.univ I *
          finiteRaceLaw rates nb n Finset.univ J <
        finiteRaceLaw rates nb n Finset.univ K *
          finiteRaceLaw rates nb n Finset.univ L) :
    ¬ RealClockEGU nb := by
  intro h
  obtain ⟨rates, hpos, hu⟩ := firstChoice_values_of_realClockEGU nb hSymm h
  have hm := hminor rates hpos
  rw [hu I hI, hu J hJ, hu K hK, hu L hL] at hm
  exact lt_irrefl _ hm

"""


class Gen:
    def __init__(self):
        self.out = [HDR]

    def graph(self, name, n, edges, doc):
        nb = graph(n, edges)
        self.out.append(f"/-- {doc} -/\ndef {name} : Fin {n} → Finset (Fin {n}) :=\n  !["
                        + ", ".join(lean_fs(x) for x in nb) + "]\n")
        self.out.append(f"theorem {name}_symm : ∀ x y, y ∈ {name} x → x ∈ {name} y := by decide\n")
        self.out.append(f"theorem {name}_irrefl : ∀ v, v ∉ {name} v := by decide\n")
        return nb

    def mis(self, name, T):
        self.out.append(f"theorem {name}_mis_{tag(T)} :\n    ({lean_fs(T)} : Finset (Fin {self.n})) ∈ maximalIndependentSets {name} := by\n  decide\n")

    def law(self, name, n, nb, T, closed, pre=""):
        self.n = n
        L = list(range(n))
        ts = race_terms(L, nb, n, frozenset(L), frozenset(T))
        hs = "\n  ".join(f"have h{i} := hr {i}" for i in range(n))
        self.out.append(f"""theorem {name}_terms_{tag(T)} :
    raceTerms (List.finRange {n}) {name} {n} Finset.univ {lean_fs(T)} =
      {lean_terms(ts)} := by
  decide

theorem {name}_law_{tag(T)} (r : Fin {n} → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r {name} {n} Finset.univ {lean_fs(T)} =
      {closed} := by
  {hs}
  rw [finiteRaceLaw_fin_eq, {name}_terms_{tag(T)}]
  simp only [raceValue, raceTermValue, List.map_cons, List.map_nil,
    List.sum_cons, List.sum_nil, List.prod_cons, List.prod_nil, mul_one, add_zero]
  {pre}field_simp
  ring
""")

    def minor(self, name, n, nb, I, J, K, L, doc):
        r = list(R[:n])
        P = {T: sp.factor(sp.together(law(n, nb, T, r))) for T in (I, J, K, L)}
        for T in (I, J, K, L):
            self.mis(name, T)
            self.law(name, n, nb, T, to_lean(P[T]))
        expr = sp.cancel(sp.together(P[K] * P[L] - P[I] * P[J]))
        N, D = sp.fraction(expr)
        assert all(c > 0 for c in sp.Poly(sp.expand(N), *r).coeffs())
        assert all(c > 0 for c in sp.Poly(sp.expand(D), *r).coeffs())
        lhs = f"({to_lean(P[K])}) * ({to_lean(P[L])}) - ({to_lean(P[I])}) * ({to_lean(P[J])})"
        hs = "\n  ".join(f"have h{i} := hr {i}" for i in range(n))
        tI, tJ, tK, tL = map(tag, (I, J, K, L))
        self.out.append(f"""/-- Strict output minor for all strictly positive rates. -/
theorem {name}_strict_minor (r : Fin {n} → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r {name} {n} Finset.univ {lean_fs(I)} *
        finiteRaceLaw r {name} {n} Finset.univ {lean_fs(J)} <
      finiteRaceLaw r {name} {n} Finset.univ {lean_fs(K)} *
        finiteRaceLaw r {name} {n} Finset.univ {lean_fs(L)} := by
  {hs}
  rw [{name}_law_{tI} r hr, {name}_law_{tJ} r hr, {name}_law_{tK} r hr, {name}_law_{tL} r hr]
  have key : {lhs} =
      ({to_lean(sp.factor(N))}) / ({to_lean(sp.factor(D))}) := by
    field_simp
    ring
  have hpos : 0 < ({to_lean(sp.factor(N))}) / ({to_lean(sp.factor(D))}) := by positivity
  linarith

/-- **{doc}** -/
theorem {name}_not_realClockEGU : ¬ RealClockEGU {name} :=
  not_realClockEGU_of_strict_minor {name} {name}_symm {lean_fs(I)} {lean_fs(J)} {lean_fs(K)} {lean_fs(L)}
    {name}_mis_{tI} {name}_mis_{tJ} {name}_mis_{tK} {name}_mis_{tL} {name}_strict_minor
""")


g = Gen()
# ---------------- P5 ----------------
p5 = g.graph("p5Nb", 5, [(0, 1), (1, 2), (2, 3), (3, 4)], "The path P5: 0–1–2–3–4.")
g.n = 5
g.minor("p5Nb", 5, p5, (0, 3), (1, 4), (0, 2, 4), (1, 3),
        "IG-N2 (Lean): P5 is not EGU under genuine exponential clocks.")
# ---------------- cone over P5 ----------------
cone = g.graph("coneP5Nb", 6, [(0, 1), (1, 2), (2, 3), (3, 4)] + [(i, 5) for i in range(5)],
               "The cone K1 ∨ P5 (atlas index 68 up to relabelling): apex 5.")
g.n = 6
g.minor("coneP5Nb", 6, cone, (0, 3), (1, 4), (0, 2, 4), (1, 3),
        "IG-N4 (Lean): the cone over P5 is not EGU under genuine exponential clocks.")

# ---------------- C6 ----------------
c6 = g.graph("c6Nb", 6, [(i, (i + 1) % 6) for i in range(6)], "The six-cycle C6.")
g.n = 6
c6forms = {
    (0, 3): "r 0 * r 3 / ((r 2 + r 4 + r 3) * (r 5 + r 1 + r 0))",
    (2, 5): "r 2 * r 5 / ((r 0 + r 4 + r 5) * (r 3 + r 1 + r 2))",
    (1, 4): "r 4 * r 1 / ((r 0 + r 2 + r 1) * (r 3 + r 5 + r 4))",
}
for T, form in c6forms.items():
    g.mis("c6Nb", T)
    g.law("c6Nb", 6, c6, T, form)
g.out.append("""theorem c6Nb_mis_card : (maximalIndependentSets c6Nb).card = 5 := by decide

/-- **IG-N1 (Lean): C6 is not EGU under genuine exponential clocks.** -/
theorem c6Nb_not_realClockEGU : ¬ RealClockEGU c6Nb := by
  intro h
  obtain ⟨r, hr, hu⟩ := firstChoice_values_of_realClockEGU c6Nb c6Nb_symm h
  have e03 := hu _ c6Nb_mis_03
  have e25 := hu _ c6Nb_mis_25
  have e14 := hu _ c6Nb_mis_14
  rw [c6Nb_mis_card, c6Nb_law_03 r hr] at e03
  rw [c6Nb_mis_card, c6Nb_law_25 r hr] at e25
  rw [c6Nb_mis_card, c6Nb_law_14 r hr] at e14
  norm_num at e03 e25 e14
  exact c6_opposite_pairs_not_all_one_fifth (r 0) (r 2) (r 4) (r 3) (r 5) (r 1)
    (hr 0) (hr 2) (hr 4) (hr 3) (hr 5) (hr 1)
    ⟨by rw [e03], by rw [e25], by rw [e14]⟩
""")

# ---------------- P6 ----------------
p6 = g.graph("p6Nb", 6, [(0, 1), (1, 2), (2, 3), (3, 4), (4, 5)], "The path P6: 0–1–2–3–4–5.")
g.n = 6
r6 = list(R)
u = R[1] / (R[0] + R[1] + R[2])
v = R[4] / (R[3] + R[4] + R[5])
g.mis("p6Nb", (1, 4))
g.law("p6Nb", 6, p6, (1, 4), "r 1 / (r 0 + r 1 + r 2) * (r 4 / (r 3 + r 4 + r 5))")
P025 = sp.factor(sp.together(law(6, p6, (0, 2, 5), r6)))
P035 = sp.factor(sp.together(law(6, p6, (0, 3, 5), r6)))
for T, Pt in (((0, 2, 5), P025), ((0, 3, 5), P035)):
    g.mis("p6Nb", T)
    g.law("p6Nb", 6, p6, T, to_lean(Pt))
expr = sp.cancel(sp.together((1 - u) * (1 - v) - P025 - P035))
N, D = sp.fraction(expr)
assert all(c > 0 for c in sp.Poly(sp.expand(N), *r6).coeffs())
assert all(c > 0 for c in sp.Poly(sp.expand(D), *r6).coeffs())
hs = "\n  ".join(f"have h{i} := hr {i}" for i in range(6))
g.out.append(f"""theorem p6Nb_mis_card : (maximalIndependentSets p6Nb).card = 5 := by decide

/-- The two outputs containing both endpoints lie below the product of
the two independent triple-race failure probabilities. -/
theorem p6Nb_endpoint_bound (r : Fin 6 → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r p6Nb 6 Finset.univ {{0, 2, 5}} +
        finiteRaceLaw r p6Nb 6 Finset.univ {{0, 3, 5}} ≤
      (1 - r 1 / (r 0 + r 1 + r 2)) * (1 - r 4 / (r 3 + r 4 + r 5)) := by
  {hs}
  rw [p6Nb_law_025 r hr, p6Nb_law_035 r hr]
  have key : (1 - r 1 / (r 0 + r 1 + r 2)) * (1 - r 4 / (r 3 + r 4 + r 5)) -
      ({to_lean(P025)}) - ({to_lean(P035)}) =
      ({to_lean(sp.factor(N))}) / ({to_lean(sp.factor(D))}) := by
    field_simp
    ring
  have hpos : 0 < ({to_lean(sp.factor(N))}) / ({to_lean(sp.factor(D))}) := by positivity
  linarith

/-- **IG-N3 (Lean): P6 is not EGU under genuine exponential clocks.** -/
theorem p6Nb_not_realClockEGU : ¬ RealClockEGU p6Nb := by
  intro h
  obtain ⟨r, hr, hu⟩ := firstChoice_values_of_realClockEGU p6Nb p6Nb_symm h
  have e14 := hu _ p6Nb_mis_14
  have e025 := hu _ p6Nb_mis_025
  have e035 := hu _ p6Nb_mis_035
  rw [p6Nb_mis_card] at e14 e025 e035
  have hb := p6Nb_endpoint_bound r hr
  rw [e025, e035] at hb
  rw [p6Nb_law_14 r hr] at e14
  have h0 := hr 0
  have h1 := hr 1
  have h2 := hr 2
  have h3 := hr 3
  have h4 := hr 4
  have h5 := hr 5
  exact p6_bottleneck_impossible (r 1 / (r 0 + r 1 + r 2)) (r 4 / (r 3 + r 4 + r 5))
    (by positivity) (by positivity) (by rw [e14]; norm_num) (by linarith)
""")

# ---------------- corona P3 ----------------
cor = g.graph("coronaP3Nb", 6, [(0, 1), (1, 2), (0, 3), (1, 4), (2, 5)],
              "Pendant corona of P3 (atlas index 3 up to relabelling): centres 0–1–2, leaves 3,4,5.")
g.n = 6
X = "(r 0 / (r 0 + r 3))"
Y = "(r 2 / (r 2 + r 5))"
S = "coronaP3Survival (r 1) (r 4)"
cforms = {
    (3, 4, 5): f"((1 - {X}) * (1 - {Y})) * {S} 0",
    (0, 4, 5): f"({X} * (1 - {Y})) * {S} (r 0 + r 3)",
    (2, 3, 4): f"((1 - {X}) * {Y}) * {S} (r 2 + r 5)",
    (0, 2, 4): f"({X} * {Y}) * {S} (r 0 + r 3 + (r 2 + r 5))",
}
for T, form in cforms.items():
    g.mis("coronaP3Nb", T)
    g.law("coronaP3Nb", 6, cor, T, form, pre="unfold coronaP3Survival\n  ")
g.out.append(f"""/-- Strict corona(P3) minor for all strictly positive rates. -/
theorem coronaP3Nb_strict_minor (r : Fin 6 → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r coronaP3Nb 6 Finset.univ {{3, 4, 5}} *
        finiteRaceLaw r coronaP3Nb 6 Finset.univ {{0, 2, 4}} <
      finiteRaceLaw r coronaP3Nb 6 Finset.univ {{0, 4, 5}} *
        finiteRaceLaw r coronaP3Nb 6 Finset.univ {{2, 3, 4}} := by
  have h0 := hr 0
  have h1 := hr 1
  have h2 := hr 2
  have h3 := hr 3
  have h4 := hr 4
  have h5 := hr 5
  rw [coronaP3Nb_law_345 r hr, coronaP3Nb_law_024 r hr, coronaP3Nb_law_045 r hr,
    coronaP3Nb_law_234 r hr]
  have hx : 0 < {X} := by positivity
  have hx1 : {X} < 1 := by rw [div_lt_one (by positivity)]; linarith
  have hy : 0 < {Y} := by positivity
  have hy1 : {Y} < 1 := by rw [div_lt_one (by positivity)]; linarith
  exact coronaP3_strict_minor _ _ (r 1) (r 4) (r 0 + r 3) (r 2 + r 5)
    hx hx1 hy hy1 h1 h4 (by positivity) (by positivity)

/-- **IG-N5, m = 2 (Lean): the pendant corona of P3 is not EGU under
genuine exponential clocks.** -/
theorem coronaP3Nb_not_realClockEGU : ¬ RealClockEGU coronaP3Nb :=
  not_realClockEGU_of_strict_minor coronaP3Nb coronaP3Nb_symm {{3, 4, 5}} {{0, 2, 4}}
    {{0, 4, 5}} {{2, 3, 4}} coronaP3Nb_mis_345 coronaP3Nb_mis_024 coronaP3Nb_mis_045
    coronaP3Nb_mis_234 coronaP3Nb_strict_minor
""")

g.out.append("end InverseGreedy\n")
dest = sys.argv[1] if len(sys.argv) > 1 else "InverseGreedy/SmallGraphObstructions.lean"
open(dest, "w").write("\n".join(g.out))
print("wrote", dest)
