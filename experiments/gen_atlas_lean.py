S3 = sp.Symbol('s', positive=True)     # sqrt 3
BETA = sp.Symbol('beta', positive=True)  # cuberoot(4) - 1


def lean_fs(s):
    s = sorted(s)
    return "∅" if not s else "{" + ", ".join(map(str, s)) + "}"


def tag(T):
    return "".join(map(str, sorted(T))) or "e"


def to_lean(expr, subs=None):
    s = sp.sstr(expr)
    s = re.sub(r"x(\d)", r"⟪\1⟫", s)
    s = s.replace("**", "^")
    if subs is None:
        s = re.sub(r"⟪(\d)⟫\^", r"(r \1)^", s)
        s = re.sub(r"⟪(\d)⟫", r"r \1", s)
    else:
        s = re.sub(r"⟪(\d)⟫", lambda m: "(" + subs[int(m.group(1))] + ")", s)
    s = s.replace("beta", "β").replace("s", "s3") if False else s
    return s


def lean_val(e):
    s = sp.sstr(e).replace("**", "^")
    s = re.sub(r"\bs\b", "√3", s)
    s = re.sub(r"\bbeta\b", "β", s)
    return s


def nb_lean(n, nb):
    return "![" + ", ".join(lean_fs(x) for x in nb) + "]"


def qlit(x):
    x = Fraction(x)
    return f"{x.numerator}" if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


