for r_ in rows:
    n, idx = r_['n'], r_['index']
    if r_['status'] == 'unresolved':
        continue
    name = f"atlas{n}_{idx}"
    chunks.append((name, len(out)))
    edges = [tuple(e) for e in r_['edges']]
    nb = graph(n, edges)
    out.append(f"/-- NetworkX connected atlas n={n} index {idx}: {r_['certificate'].split(';')[0]}. -/\n"
               f"def {name} : Fin {n} → Finset (Fin {n}) := {nb_lean(n, nb)}\n")
    out.append(f"theorem {name}_symm : ∀ x y, y ∈ {name} x → x ∈ {name} y := by decide\n")
    out.append(f"theorem {name}_irrefl : ∀ v, v ∉ {name} v := by decide\n")
    cert = r_['certificate']
    if r_['status'] == 'proved-negative':
        neg_names.append(name)
        if cert.startswith('P5 strict'):
            emit_iso_negative(name, n, edges, 'p5Nb')
        elif cert.startswith('S009'):
            emit_iso_negative(name, n, edges, 'coronaP3Nb')
        elif cert.startswith('P6'):
            emit_iso_negative(name, n, edges, 'p6Nb')
        elif cert.startswith('C6'):
            emit_iso_negative(name, n, edges, 'c6Nb')
        elif cert.startswith('K1 join P5'):
            emit_iso_negative(name, n, edges, 'coneP5Nb')
        elif cert.startswith('S007 false-twin contraction'):
            u, v = r_['twin_pair']
            emit_twin(name, n, edges, u, v, 'p5Nb', False)
        else:
            raise AssertionError(cert)
        continue
    # positives
    rates = None
    if cert.startswith('cograph') or cert.startswith('exact rational') or cert.startswith('S005 exact positive') or cert.startswith('S006'):
        rates = [Fraction(x) for x in r_['rates']]
    elif cert.startswith('S007 false-twin lift'):
        u, v = r_['twin_pair']
        p = r_['contracted_n5_index']
        g6 = nx.Graph(); g6.add_nodes_from(range(n)); g6.add_edges_from(edges)
        red = g6.copy(); red.remove_node(v)
        prow = five_rows[p]
        if prow['certificate'].startswith('S005 exact Q(sqrt(3))'):
            emit_twin(name, n, edges, u, v, f"atlas5_{p}", True)
            continue
        rates = list(lift_rates(red, p, u, v, five_atlas, [Fraction(x) for x in prow['rates']]))
    elif cert.startswith('P4'):
        # path order of the atlas P4
        g4 = nx.Graph(); g4.add_edges_from(edges)
        m = next(nx.algorithms.isomorphism.GraphMatcher(g4, nx.path_graph(4)).isomorphisms_iter())
        base = [1 + S3, sp.Integer(2), sp.Integer(2), 1 + S3]
        emit_algebraic(name, n, nb, [base[m[w]] for w in range(4)], 'sqrt3')
        continue
    elif cert.startswith('S005 exact Q(sqrt(3))'):
        emit_algebraic(name, n, nb, [1 + S3, 2 + 2 * S3 / 3, 1 + S3, sp.Integer(2), sp.Integer(2)], 'sqrt3')
        continue
    elif cert.startswith('S008'):
        emit_clique_corona(name, n, edges)
        continue
    else:
        raise AssertionError(cert)
    adj = egraph(n, edges)
    assert is_uniform(law_by_recursion(adj, tuple(rates))), name
    qv = "![" + ", ".join(qlit(x) for x in rates) + "]"
    out.append(f"""theorem {name}_egu : RealClockEGU {name} :=
  realClockEGU_of_ratWitness {name} {qv} (by decide +kernel) {name}_symm (by decide +kernel)
""")
    pos_names.append(name)

