"""Generate InverseGreedy/AtlasCertificates.lean from the census.

Every decided connected graph of order <= 6 (NetworkX atlas labelling)
receives a Lean theorem about genuine exponential clocks:
* positives with rational witnesses: `realClockEGU_of_ratWitness` with all
  hypotheses checked by kernel `decide +kernel`;
* positives with algebraic witnesses (sqrt 3, cube root of 4): closed-form
  law lemmas (`decide` + `field_simp; ring`) and `linear_combination`;
* negatives: relabelling to the S041 obstruction graphs, or a strict
  positive-coefficient minor certificate (false twins of P5).
Nothing here is trusted by Lean; it only writes checkable proofs.
"""
