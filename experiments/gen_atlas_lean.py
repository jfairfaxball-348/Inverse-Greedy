def find_perm(edges_a, n, edges_b):
    ga = nx.Graph(); ga.add_nodes_from(range(n)); ga.add_edges_from(edges_a)
    gb = nx.Graph(); gb.add_nodes_from(range(n)); gb.add_edges_from(edges_b)
    m = nx.algorithms.isomorphism.GraphMatcher(ga, gb)
    return next(m.isomorphisms_iter())


def emit_iso_negative(name, n, edges, mine):
    mn, medges = MINE[mine]
    assert mn == n
    f = find_perm(edges, n, medges)
    g = {v: k for k, v in f.items()}
    fv = "![" + ", ".join(str(f[i]) for i in range(n)) + "]"
    gv = "![" + ", ".join(str(g[i]) for i in range(n)) + "]"
    out.append(f"""theorem {name}_not_realClockEGU : ¬ RealClockEGU {name} := by
  let e : Fin {n} ≃ Fin {n} := ⟨{fv}, {gv}, by decide, by decide⟩
  have hnb : ∀ a, {mine} (e a) = ({name} a).map e.toEmbedding := by decide
  exact fun h => {mine}_not_realClockEGU
    ((realClockEGU_congr_equiv e {name} {mine} hnb {name}_symm {mine}_symm).mp h)
""")


def law_lemma(name, n, nb, T, N, D):
    L = list(range(n))
    ts = race_terms(L, nb, n, frozenset(L), frozenset(T))
    terms = "[" + ", ".join("[" + ", ".join(f"({v}, [{', '.join(map(str, S))}])" for v, S in t) + "]" for t in ts) + "]"
    hs = "\n  ".join(f"have h{i} := hr {i}" for i in range(n))
    out.append(f"""theorem {name}_terms_{tag(T)} :
    raceTerms (List.finRange {n}) {name} {n} Finset.univ {lean_fs(T)} =
      {terms} := by
  decide +kernel

set_option maxHeartbeats 2000000 in
theorem {name}_law_{tag(T)} (r : Fin {n} → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r {name} {n} Finset.univ {lean_fs(T)} = ({N}) / ({D}) := by
  {hs}
  rw [finiteRaceLaw_fin_eq, {name}_terms_{tag(T)}]
  simp only [raceValue, raceTermValue, List.map_cons, List.map_nil,
    List.sum_cons, List.sum_nil, List.prod_cons, List.prod_nil, mul_one, add_zero]
  field_simp
  ring
""")


def emit_minor_negative(name, n, nb, I, J, K, L):
    r = list(X[:n])
    P = {T: sp.factor(sp.together(law(n, nb, T, r))) for T in (I, J, K, L)}
    strs = {}
    for T in (I, J, K, L):
        Nn, Dd = sp.fraction(P[T])
        strs[T] = f"({to_lean(Nn)}) / ({to_lean(Dd)})"
        out.append(f"theorem {name}_mis_{tag(T)} : ({lean_fs(T)} : Finset (Fin {n})) ∈ maximalIndependentSets {name} := by decide +kernel\n")
        law_lemma(name, n, nb, T, to_lean(Nn), to_lean(Dd))
    expr = sp.cancel(sp.together(P[K] * P[L] - P[I] * P[J]))
    Nn, Dd = sp.fraction(expr)
    assert all(c > 0 for c in sp.Poly(sp.expand(Nn), *r).coeffs())
    assert all(c > 0 for c in sp.Poly(sp.expand(Dd), *r).coeffs())
    hs = "\n  ".join(f"have h{i} := hr {i}" for i in range(n))
    tI, tJ, tK, tL = map(tag, (I, J, K, L))
    lhs = f"({strs[K]}) * ({strs[L]}) - ({strs[I]}) * ({strs[J]})"
    out.append(f"""set_option maxHeartbeats 2000000 in
theorem {name}_strict_minor (r : Fin {n} → ℝ) (hr : ∀ v, 0 < r v) :
    finiteRaceLaw r {name} {n} Finset.univ {lean_fs(I)} *
        finiteRaceLaw r {name} {n} Finset.univ {lean_fs(J)} <
      finiteRaceLaw r {name} {n} Finset.univ {lean_fs(K)} *
        finiteRaceLaw r {name} {n} Finset.univ {lean_fs(L)} := by
  {hs}
  rw [{name}_law_{tI} r hr, {name}_law_{tJ} r hr, {name}_law_{tK} r hr, {name}_law_{tL} r hr]
  have key : {lhs} = ({to_lean(sp.factor(Nn))}) / ({to_lean(sp.factor(Dd))}) := by
    field_simp
    ring
  have hpos : 0 < ({to_lean(sp.factor(Nn))}) / ({to_lean(sp.factor(Dd))}) := by positivity
  linarith

theorem {name}_not_realClockEGU : ¬ RealClockEGU {name} :=
  not_realClockEGU_of_strict_minor {name} {name}_symm {lean_fs(I)} {lean_fs(J)} {lean_fs(K)} {lean_fs(L)}
    {name}_mis_{tI} {name}_mis_{tJ} {name}_mis_{tK} {name}_mis_{tL} {name}_strict_minor
""")


def emit_algebraic(name, n, nb, vals, kind):
    """vals: sympy expressions in S3 or BETA."""
    r = list(X[:n])
    mis = [frozenset(m) for m in mis_list(n, nb)]
    k = len(mis)
    sym = S3 if kind == 'sqrt3' else BETA
    rel = (S3 ** 2 - 3) if kind == 'sqrt3' else ((1 + BETA) ** 3 - 4)
    vstr = [lean_val(v) for v in vals]
    out.append(f"theorem {name}_mis_eq : maximalIndependentSets {name} = "
               + "{" + ", ".join(lean_fs(m) for m in sorted(mis, key=lambda s: sorted(s))) + "} := by decide +kernel\n")
    out.append(f"theorem {name}_mis_card : (maximalIndependentSets {name}).card = {k} := by decide +kernel\n")
    keys = []
    for T in sorted(mis, key=lambda s: sorted(s)):
        PT = sp.factor(sp.together(law(n, nb, T, r)))
        Nn, Dd = sp.fraction(PT)
        law_lemma(name, n, nb, T, to_lean(Nn), to_lean(Dd))
        sub = dict(zip(r, vals))
        Nv = sp.expand(Nn.subs(sub)); Dv = sp.expand(Dd.subs(sub))
        diff = sp.expand(Nv * k - Dv)
        q, rem = sp.div(sp.Poly(diff, sym), sp.Poly(sp.expand(rel), sym))
        assert rem.is_zero, (name, T, rem)
        coeff = lean_val(q.as_expr())
        Ns = to_lean(Nn, vstr); Ds = to_lean(Dd, vstr)
        hrel = "hs" if kind == 'sqrt3' else "hβ3"
        out.append(f"""theorem {name}_key_{tag(T)} {"" if kind == 'sqrt3' else "(β : ℝ) (hβ : 0 < β) (hβ3 : (1 + β) ^ 3 = 4)"} :
    ({Ns}) / ({Ds}) = 1 / ({k} : ℝ) := by
  {"have hs : √3 ^ 2 = 3 := Real.sq_sqrt (by norm_num)" if kind == 'sqrt3' else ""}
  {"have hs0 : 0 < √3 := by positivity" if kind == 'sqrt3' else ""}
  rw [div_eq_div_iff (by positivity) (by norm_num)]
  linear_combination ({coeff}) * {hrel}
""")
        keys.append(T)
    rvec = "![" + ", ".join(vstr) + "]"
    if kind == 'sqrt3':
        pre = """  have hs0 : 0 < √3 := by positivity
"""
        bind = ""
        args = ""
    else:
        pre = """  obtain ⟨β, hβ, hβ3⟩ : ∃ β : ℝ, 0 < β ∧ (1 + β) ^ 3 = 4 := by
    refine ⟨(4 : ℝ) ^ ((3 : ℕ)⁻¹ : ℝ) - 1, ?_, ?_⟩
    · have h4 : ((4 : ℝ) ^ ((3 : ℕ)⁻¹ : ℝ)) ^ 3 = 4 :=
        Real.rpow_inv_natCast_pow (by norm_num) (by norm_num)
      have hnn : 0 ≤ (4 : ℝ) ^ ((3 : ℕ)⁻¹ : ℝ) := by positivity
      nlinarith [sq_nonneg ((4 : ℝ) ^ ((3 : ℕ)⁻¹ : ℝ) - 1)]
    · simp only [add_sub_cancel]
      exact Real.rpow_inv_natCast_pow (by norm_num) (by norm_num)
"""
        args = " β hβ hβ3"
    goals = "\n".join(
        f"  · exact ({name}_law_{tag(T)} _ hr).trans ({name}_key_{tag(T)}{args})" for T in keys)
    out.append(f"""theorem {name}_egu : RealClockEGU {name} := by
{pre}  rw [realClockEGU_iff_firstChoiceEGU _ {name}_symm]
  have hr : ∀ v, 0 < ({rvec} : Fin {n} → ℝ) v := by
    intro v; fin_cases v <;> norm_num <;> positivity
  refine ⟨_, hr, ?_⟩
  simp only [Fintype.card_fin]
  rw [{name}_mis_card, {name}_mis_eq]
  simp only [Finset.mem_insert, Finset.mem_singleton, forall_eq_or_imp, forall_eq, Nat.cast_ofNat]
  refine ⟨{", ".join("?_" for _ in keys)}⟩
{goals}
""")
    pos_names.append(name)


def mis_list(n, nb):
    adj = egraph(n, [(a, b) for a in range(n) for b in nb[a] if a < b])
    out_ = []
    for m in maximal_independent_sets(adj):
        out_.append([i for i in range(n) if (m >> i) & 1])
    return out_



def emit_twin(name, n, edges, u, v, base, base_positive):
    """atlas graph ≅ twinExtend base w, where v is the new twin of u."""
    bn, bedges = (5, MINE['p5Nb'][1]) if base == 'p5Nb' else (5, None)
    red = nx.Graph(); red.add_nodes_from(range(n)); red.add_edges_from(edges); red.remove_node(v)
    if base == 'p5Nb':
        tgt = nx.Graph(); tgt.add_nodes_from(range(5)); tgt.add_edges_from(MINE['p5Nb'][1])
    else:
        r5 = five_rows[int(base.split('_')[1])]
        tgt = nx.Graph(); tgt.add_nodes_from(range(5)); tgt.add_edges_from([tuple(e) for e in r5['edges']])
    phi = next(nx.algorithms.isomorphism.GraphMatcher(red, tgt).isomorphisms_iter())
    w = phi[u]
    fv = "![" + ", ".join("none" if x == v else f"some {phi[x]}" for x in range(n)) + "]"
    inv = {phi[x]: x for x in phi}
    gv = "![" + ", ".join(str(inv[y]) for y in range(5)) + "]"
    common = f"""  let e : Fin {n} ≃ Option (Fin 5) :=
    ⟨{fv}, fun x => x.elim ({v} : Fin {n}) {gv}, by decide, by decide⟩
  have hnb : ∀ a, twinExtend {base} {w} (e a) = ({name} a).map e.toEmbedding := by decide
  have hiso := realClockEGU_congr_equiv e {name} (twinExtend {base} {w}) hnb {name}_symm
    (twinExtend_symm {base} {base}_symm {w})
  have htw := realClockEGU_twinExtend_iff {base} {base}_symm {base}_irrefl {w}
"""
    if base_positive:
        out.append(f"""theorem {name}_egu : RealClockEGU {name} := by
{common}  exact hiso.mpr (htw.mpr {base}_egu)
""")
        pos_names.append(name)
    else:
        out.append(f"""theorem {name}_not_realClockEGU : ¬ RealClockEGU {name} := by
{common}  exact fun h => {base}_not_realClockEGU (htw.mp (hiso.mp h))
""")


def emit_clique_corona(name, n, edges):
    g6 = nx.Graph(); g6.add_nodes_from(range(n)); g6.add_edges_from(edges)
    leaves = [x for x in range(n) if g6.degree(x) == 1]
    centre_of = {l: next(iter(g6.neighbors(l))) for l in leaves}
    order = sorted(leaves)
    f = {}
    for i, l in enumerate(order):
        f[l] = f"Sum.inl {i}"; f[centre_of[l]] = f"Sum.inr {i}"
    fv = "![" + ", ".join(f"({f[x]} : Fin 3 ⊕ Fin 3)" for x in range(n)) + "]"
    gl = "![" + ", ".join(str(l) for l in order) + "]"
    gc = "![" + ", ".join(str(centre_of[l]) for l in order) + "]"
    out.append(f"""theorem {name}_egu : RealClockEGU {name} := by
  let e : Fin {n} ≃ Fin 3 ⊕ Fin 3 :=
    ⟨{fv}, fun x => Sum.elim {gl} {gc} x, by decide, by decide⟩
  have hnb : ∀ a, cliqueCoronaNb 3 (e a) = ({name} a).map e.toEmbedding := by decide
  exact (realClockEGU_congr_equiv e {name} (cliqueCoronaNb 3) hnb {name}_symm
    (cliqueCoronaNb_symm 3)).mpr (cliqueCorona_realClockEGU 3 (by norm_num))
""")
    pos_names.append(name)


